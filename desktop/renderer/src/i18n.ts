export function makeT(lang: Lang) {
  return (key: string, fallback?: string): string => {
    const hit = DICT[key]?.[lang];
    if (hit != null) return hit;
    if (lang === "en") {
      const en = DICT_EN[key];
      if (en != null) return en;
    }
    return fallback ?? key;
  };
}
export type T = ReturnType<typeof makeT>;
